def get_language() -> str:
    lang = (os.getenv("BOT_LANGUAGE") or DEFAULT_LANGUAGE).strip().lower()
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, **kwargs) -> str:
    """Return the message for `key` in the configured language.

    Falls back to English for untranslated keys, and to the key itself
    if the key is unknown (so a missing entry never crashes the bot).
    """
    text = MESSAGES.get(get_language(), {}).get(key)
    if text is None:
        text = MESSAGES[DEFAULT_LANGUAGE].get(key)
    if text is None:
        return key
    return text.format(**kwargs) if kwargs else text
